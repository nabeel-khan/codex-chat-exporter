"use strict";

const fsp = require("node:fs/promises");
const path = require("node:path");

const { extractConversation } = require("./chat-pdf");

const MARKDOWN_SIGNATURE = "<!-- Generated by Codex Chat Exporter -->";

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function escapeInline(value) {
  return escapeHtml(value)
    .replace(/([\\`*_[\]#])/g, "\\$1");
}

function escapeTableCell(value) {
  return escapeInline(value)
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, "<br>");
}

function formatTimestamp(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return `${date.toISOString().replace("T", " ").replace(/\.\d{3}Z$/, "")} UTC`;
}

function quoteBlock(value) {
  return escapeHtml(value)
    .split("\n")
    .map((line) => (line ? `> ${line}` : ">"))
    .join("\n");
}

function fencedBlock(value, language = "text") {
  const text = String(value ?? "");
  const longestRun = Math.max(0, ...(text.match(/`+/g) || []).map((run) => run.length));
  const fence = "`".repeat(Math.max(3, longestRun + 1));
  return `${fence}${language}\n${text}\n${fence}`;
}

function messageSection(message) {
  const variants = {
    user: { label: "You", activity: false },
    assistant: { label: "Codex", activity: false },
    reasoning: { label: "Reasoning summary", activity: false },
    terminal: { label: "Terminal command", activity: true, language: "text" },
    terminal_result: { label: "Terminal result", activity: true, language: "text" },
    code: { label: "Code edit", activity: true, language: "diff" },
    code_result: { label: "Edit result", activity: true, language: "text" },
  };
  const variant = variants[message.kind] || variants.assistant;
  const tool = message.toolName ? ` — ${escapeInline(message.toolName)}` : "";
  const timestamp = formatTimestamp(message.timestamp);
  const details = timestamp ? `_${escapeInline(timestamp)}_\n\n` : "";
  const body = variant.activity
    ? fencedBlock(message.text, variant.language)
    : quoteBlock(message.text);

  return `### ${variant.label}${tool}\n\n${details}${body}`;
}

function renderChatMarkdown(session, transcript) {
  const entryCount = transcript.messages.length;
  const summary = [
    `${transcript.visibleMessages} visible message${transcript.visibleMessages === 1 ? "" : "s"}`,
    `${transcript.reasoningEntries} recorded reasoning summar${transcript.reasoningEntries === 1 ? "y" : "ies"}`,
    `${transcript.terminalCommands} terminal command${transcript.terminalCommands === 1 ? "" : "s"}`,
    `${transcript.codeEdits} code edit${transcript.codeEdits === 1 ? "" : "s"}`,
    `${transcript.toolResults} matching result${transcript.toolResults === 1 ? "" : "s"}`,
  ].join(", ");
  const created = formatTimestamp(session.createdAt) || "Unknown";
  const metadata = [
    ["Project", session.project || "Unknown"],
    ["Session ID", session.sessionId || "Unknown"],
    ["Created", created],
    ["Working folder", session.cwd || "Unknown"],
    ["Source", path.basename(session.source || "Unknown")],
  ];
  const sections = transcript.messages.length > 0
    ? transcript.messages.map(messageSection).join("\n\n")
    : "_No readable conversation or activity entries were recorded for this session._";

  return `${MARKDOWN_SIGNATURE}
# ${escapeInline(session.title || "Untitled session")}

> [!IMPORTANT]
> This readable transcript may contain sensitive information and is not redacted. The adjacent JSONL file is the authoritative, complete session record.

| Field | Value |
| --- | --- |
${metadata.map(([label, value]) => `| ${label} | ${escapeTableCell(value)} |`).join("\n")}

## Conversation

_${entryCount} transcript entr${entryCount === 1 ? "y" : "ies"}: ${summary}. Encrypted internal reasoning is not decrypted._

${sections}
`;
}

async function generateChatMarkdown(session, destination, transcript) {
  const conversation = transcript || await extractConversation(session.source);
  const markdown = renderChatMarkdown(session, conversation);
  const tempDestination = `${destination}.tmp-${process.pid}-${Date.now()}`;

  try {
    await fsp.writeFile(tempDestination, markdown, "utf8");
    await fsp.rename(tempDestination, destination);
  } catch (error) {
    await fsp.rm(tempDestination, { force: true }).catch(() => {});
    throw error;
  }

  return {
    messages: conversation.messages.length,
    reasoningEntries: conversation.reasoningEntries,
    terminalCommands: conversation.terminalCommands,
    codeEdits: conversation.codeEdits,
    toolResults: conversation.toolResults,
  };
}

async function isUsableMarkdown(filePath) {
  let handle;
  try {
    handle = await fsp.open(filePath, "r");
    const header = Buffer.alloc(256);
    const { bytesRead } = await handle.read(header, 0, header.length, 0);
    const text = header.subarray(0, bytesRead).toString("utf8");
    return text.startsWith(MARKDOWN_SIGNATURE) && text.includes("\n# ");
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  } finally {
    await handle?.close();
  }
}

module.exports = {
  MARKDOWN_SIGNATURE,
  fencedBlock,
  generateChatMarkdown,
  isUsableMarkdown,
  renderChatMarkdown,
};
