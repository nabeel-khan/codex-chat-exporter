"use strict";

const fsp = require("node:fs/promises");
const path = require("node:path");

const { extractConversation } = require("./chat-pdf");

const HTML_SIGNATURE = "<!-- Generated by Codex Chat Exporter -->";

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function formatTimestamp(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return `${date.toISOString().replace("T", " ").replace(/\.\d{3}Z$/, "")} UTC`;
}

function messageCard(message) {
  const variants = {
    user: { label: "You", className: "user", activity: false },
    assistant: { label: "Codex", className: "assistant", activity: false },
    reasoning: { label: "Reasoning summary", className: "reasoning", activity: false },
    terminal: { label: "Terminal command", className: "terminal", activity: true },
    terminal_result: { label: "Terminal result", className: "terminal-result", activity: true },
    code: { label: "Code edit", className: "code", activity: true },
    code_result: { label: "Edit result", className: "code-result", activity: true },
  };
  const variant = variants[message.kind] || variants.assistant;
  const tool = message.toolName ? ` <span class="tool">${escapeHtml(message.toolName)}</span>` : "";
  const timestamp = formatTimestamp(message.timestamp);
  const body = variant.activity
    ? `<pre><code>${escapeHtml(message.text)}</code></pre>`
    : `<div class="message-body">${escapeHtml(message.text)}</div>`;

  return `<article class="message ${variant.className}">
  <header><strong>${variant.label}</strong>${tool}${timestamp ? `<time>${escapeHtml(timestamp)}</time>` : ""}</header>
  ${body}
</article>`;
}

