"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");

const { generateChatHtml, isUsableHtml, renderChatHtml } = require("../chat-html");

test("renders a standalone, escaped HTML transcript", () => {
  const html = renderChatHtml({
    title: "Fix <login>",
    project: "acme",
    sessionId: "session-1",
    createdAt: "2026-01-01T00:00:00Z",
    cwd: "/work/acme",
    source: "/sessions/rollout-session-1.jsonl",
  }, {
    messages: [
      { kind: "user", text: "Run <script>alert(1)</script>", timestamp: "2026-01-01T00:00:01Z" },
      { kind: "terminal", text: "npm test && echo <done>", timestamp: "2026-01-01T00:00:02Z", toolName: "exec_command" },
    ],
    visibleMessages: 1,
    reasoningEntries: 0,
    terminalCommands: 1,
    codeEdits: 0,
    toolResults: 0,
  });

  assert.match(html, /^<!-- Generated by Codex Chat Exporter -->\n<!doctype html>/);
  assert.match(html, /Content-Security-Policy/);
  assert.doesNotMatch(html, /<script>/);
  assert.match(html, /Run &lt;script&gt;alert\(1\)&lt;\/script&gt;/);
  assert.match(html, /<pre><code>npm test &amp;&amp; echo &lt;done&gt;<\/code><\/pre>/);
});

test("generates a recognizable HTML file from a session", async (t) => {
  const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), "codex-html-test-"));
  t.after(() => fs.rm(tempRoot, { recursive: true, force: true }));
  const source = path.join(tempRoot, "session.jsonl");
  const destination = path.join(tempRoot, "session.html");
  const records = [
    { timestamp: "2026-01-01T00:00:00Z", type: "event_msg", payload: { type: "user_message", message: "Export this" } },
    { timestamp: "2026-01-01T00:00:01Z", type: "event_msg", payload: { type: "agent_message", message: "Done" } },
  ];
  await fs.writeFile(source, `${records.map(JSON.stringify).join("\n")}\n`);

  const result = await generateChatHtml({
    title: "Synthetic session",
    project: "demo",
    source,
  }, destination);

  assert.equal(result.messages, 2);
  assert.equal(await isUsableHtml(destination), true);
  assert.match(await fs.readFile(destination, "utf8"), /<strong>Codex<\/strong>/);
});
