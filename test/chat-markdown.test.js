"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");

const {
  fencedBlock,
  generateChatMarkdown,
  isUsableMarkdown,
  renderChatMarkdown,
} = require("../chat-markdown");

test("renders metadata, messages, and activity as readable Markdown", () => {
  const session = {
    title: "Fix [login]",
    project: "acme",
    sessionId: "session-1",
    createdAt: "2026-01-01T00:00:00Z",
    cwd: "/work/acme",
    source: "/sessions/rollout-session-1.jsonl",
  };
  const transcript = {
    messages: [
      { kind: "user", text: "Please fix it. <script>alert(1)</script>", timestamp: "2026-01-01T00:00:01Z" },
      { kind: "terminal", text: "echo ```", timestamp: "2026-01-01T00:00:02Z", toolName: "exec_command" },
      { kind: "code", text: "-old\n+new", timestamp: "2026-01-01T00:00:03Z", toolName: "apply_patch" },
    ],
    visibleMessages: 1,
    reasoningEntries: 0,
    terminalCommands: 1,
    codeEdits: 1,
    toolResults: 0,
  };

  const markdown = renderChatMarkdown(session, transcript);
  assert.match(markdown, /^<!-- Generated by Codex Chat Exporter -->/);
  assert.ok(markdown.includes("# Fix \\[login\\]"));
  assert.match(markdown, /### You/);
  assert.match(markdown, /> Please fix it\./);
  assert.doesNotMatch(markdown, /<script>/);
  assert.match(markdown, /&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
  assert.ok(markdown.includes("### Terminal command — exec\\_command"));
  assert.match(markdown, /````text\necho ```\n````/);
  assert.match(markdown, /```diff\n-old\n\+new\n```/);
});

test("uses a fence longer than any backtick run in activity text", () => {
  assert.equal(fencedBlock("before ````` after"), "``````text\nbefore ````` after\n``````");
});

test("generates a recognizable Markdown file from a session", async (t) => {
  const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), "codex-markdown-test-"));
  t.after(() => fs.rm(tempRoot, { recursive: true, force: true }));
  const source = path.join(tempRoot, "session.jsonl");
  const destination = path.join(tempRoot, "session.md");
  const records = [
    { timestamp: "2026-01-01T00:00:00Z", type: "event_msg", payload: { type: "user_message", message: "Export this" } },
    { timestamp: "2026-01-01T00:00:01Z", type: "event_msg", payload: { type: "agent_message", message: "Done" } },
  ];
  await fs.writeFile(source, `${records.map(JSON.stringify).join("\n")}\n`);

  const result = await generateChatMarkdown({
    title: "Synthetic session",
    project: "demo",
    source,
  }, destination);

  assert.equal(result.messages, 2);
  assert.equal(await isUsableMarkdown(destination), true);
  assert.match(await fs.readFile(destination, "utf8"), /### Codex\n/);
});
